#!/usr/bin/env node
/**
 * Declare the tables that only ever get created at runtime.
 *
 * Several controllers create their own table on first use, inside a catch block
 * that checks for "no such table". It works in development, where the app owns
 * the database, and it is a poor thing to rely on in production: the application
 * role usually has no DDL rights, two concurrent first-requests race each other,
 * and until someone happens to call the endpoint the table simply is not there.
 * medical_requests is the clearest case -- nothing declares it, so an emergency
 * medical request depends on an earlier request having already failed once.
 *
 * The definitions are lifted from the CREATE TABLE statements in the source
 * rather than rewritten, so the migrated shape matches what the code expects.
 * The SQLite variant is translated by type; the PostgreSQL one is kept as-is.
 *
 *   node scripts/generate-runtime-table-migration.js
 */
const fs = require('fs');
const path = require('path');

const BACKEND = path.resolve(__dirname, '..');
const SRC = path.join(BACKEND, 'src');
const MIG = path.join(SRC, 'migrations');

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (e.name.endsWith('.js')) out.push(p);
  }
  return out;
}

/** Every CREATE TABLE statement found in JS source, keyed by table name. */
function runtimeCreates() {
  const found = {};
  for (const file of walk(SRC)) {
    const js = fs.readFileSync(file, 'utf8');
    const re = /CREATE TABLE(?:\s+IF NOT EXISTS)?\s+["`']?(\w+)["`']?\s*\(/gi;
    let m;
    while ((m = re.exec(js))) {
      const table = m[1].toLowerCase();
      // Walk from the opening paren to its match so nested type parens such as
      // VARCHAR(255) and DECIMAL(10,2) do not end the definition early.
      let depth = 0;
      let i = m.index + m[0].length - 1;
      const start = i;
      for (; i < js.length; i++) {
        if (js[i] === '(') depth++;
        else if (js[i] === ')') { depth--; if (depth === 0) break; }
      }
      if (depth !== 0) continue;
      const body = js.slice(start + 1, i);
      if (!/\w+\s+\w/.test(body)) continue;
      if (!found[table]) found[table] = { body, file: path.relative(BACKEND, file) };
    }
  }
  return found;
}

/** Column names already declared for `table` anywhere in the migration set. */
function migrationTables() {
  const names = new Set();
  for (const f of fs.readdirSync(MIG).filter((x) => x.endsWith('.sql'))) {
    const sql = fs.readFileSync(path.join(MIG, f), 'utf8').replace(/--[^\n]*/g, '');
    for (const m of sql.matchAll(/CREATE TABLE(?:\s+IF NOT EXISTS)?\s+"?(\w+)"?/gi)) {
      names.add(m[1].toLowerCase());
    }
  }
  return names;
}

/** PostgreSQL types -> SQLite equivalents. */
function toSqlite(body) {
  return body
    .replace(/\bSERIAL\b/gi, 'INTEGER')
    .replace(/\bVARCHAR\s*\(\s*\d+\s*\)/gi, 'TEXT')
    .replace(/\bBOOLEAN\b/gi, 'INTEGER')
    .replace(/\bTIMESTAMPTZ\b/gi, 'DATETIME')
    .replace(/\bTIMESTAMP\b/gi, 'DATETIME')
    .replace(/\bJSONB?\b/gi, 'TEXT')
    .replace(/\bUUID\b/gi, 'TEXT')
    .replace(/\bDEFAULT\s+true\b/gi, 'DEFAULT 1')
    .replace(/\bDEFAULT\s+false\b/gi, 'DEFAULT 0')
    .replace(/\bNOW\s*\(\s*\)/gi, 'CURRENT_TIMESTAMP')
    .replace(/\bDEFAULT\s+uuid_generate_v4\s*\(\s*\)/gi, '');
}

function main() {
  const creates = runtimeCreates();
  const declared = migrationTables();

  const missing = Object.entries(creates)
    .filter(([t]) => !declared.has(t) && t !== 'schema_migrations')
    .sort(([a], [b]) => a.localeCompare(b));

  if (!missing.length) {
    console.log('\nEvery table created at runtime is already declared by a migration.\n');
    return;
  }

  const header = (engine) => `-- Migration 082${engine === 'sqlite' ? ' (SQLite)' : ''}: tables that were only ever created at runtime
--
-- Each table below is created by a controller on first use, inside a catch block
-- that tests for "no such table". That works in development, where the
-- application owns the database, and is unsafe in production: the application
-- role usually has no DDL rights, two concurrent first-requests race, and until
-- somebody calls the endpoint the table does not exist at all.
--
-- medical_requests is the clearest case. Nothing declares it, so logging an
-- emergency medical request only works because an earlier request already failed
-- and created the table on its way out.
--
-- The definitions are lifted from the CREATE TABLE statements in the source, not
-- rewritten, so the migrated shape is the one the code already expects. The
-- runtime fallbacks can stay where they are -- they simply stop being reachable.
--
-- Generated by scripts/generate-runtime-table-migration.js.
`;

  const sqliteOut = [header('sqlite')];
  const pgOut = [header('pg')];

  for (const [table, info] of missing) {
    sqliteOut.push('', `-- ${table} (from ${info.file})`);
    sqliteOut.push(`CREATE TABLE IF NOT EXISTS ${table} (${toSqlite(info.body).replace(/\s+$/, '')}\n);`);
    pgOut.push('', `-- ${table} (from ${info.file})`);
    pgOut.push(`CREATE TABLE IF NOT EXISTS ${table} (${info.body.replace(/\s+$/, '')}\n);`);
  }

  fs.writeFileSync(path.join(MIG, '082_runtime_created_tables.sqlite.sql'), sqliteOut.join('\n') + '\n');
  fs.writeFileSync(path.join(MIG, '082_runtime_created_tables.sql'), pgOut.join('\n') + '\n');

  console.log('\nTables created at runtime but never declared');
  console.log('='.repeat(78));
  console.log(`Found: ${missing.length}\n`);
  for (const [t, i] of missing) console.log(`  ${t.padEnd(28)} ${i.file}`);
  console.log('\nWritten: 082_runtime_created_tables.sql / .sqlite.sql\n');
}

main();
