#!/usr/bin/env node
/**
 * Restore columns that the DDL declares but the database does not have.
 *
 * Tables are re-declared across migrations, and both engines treat
 * CREATE TABLE IF NOT EXISTS as a no-op once the table exists. A later
 * migration that re-declares a table with extra columns therefore adds nothing
 * and still reports success. marketplace_listings lost latitude/longitude that
 * way, which broke POST /marketplace outright and left its radius filter
 * matching every listing.
 *
 * Deciding "did this CREATE take effect?" from migration ordering turned out to
 * be unreliable — successive attempts put the count at 95, then 102, then 111,
 * and spot-checks against the database contradicted all three. So this reads
 * the live schema and diffs it against every column the DDL declares. Whatever
 * is declared but absent is genuinely missing, whatever the cause.
 *
 * Additive only: nothing is dropped or retyped, so it cannot lose data, and
 * re-running is safe.
 *
 *   node scripts/repair-noop-creates.js           # report
 *   node scripts/repair-noop-creates.js --write   # emit migration 069
 */
const fs = require('fs');
const path = require('path');

const MIG = path.resolve(__dirname, '..', 'src', 'migrations');
const GENERATED = new Set([
  '068_pg_parity_missing_tables.sql',
  '069_repair_noop_creates.sql',
  '069_repair_noop_creates.sqlite.sql',
]);

function ddlFiles(sqlite) {
  const all = fs.readdirSync(MIG)
    .filter((f) => f.endsWith('.sql') && !GENERATED.has(f))
    .filter((f) => (sqlite ? f.includes('.sqlite.') : !f.includes('.sqlite.')));
  // run.js executes init first; a plain sort() would put it last ('0' < 'i').
  const init = all.filter((f) => /^init\./.test(f)).sort();
  const rest = all.filter((f) => !/^init\./.test(f)).sort();
  return [...init, ...rest];
}

function parseColumns(body) {
  const cols = new Map();
  for (const raw of body.split('\n')) {
    const line = raw.trim().replace(/,$/, '');
    if (!line || line.startsWith('--')) continue;
    if (/^(PRIMARY KEY|UNIQUE|CHECK|FOREIGN KEY|CONSTRAINT)\b/i.test(line)) continue;
    const m = line.match(/^"?(\w+)"?\s+([A-Za-z][\w()]*)\s*(.*)$/);
    if (!m) continue;
    cols.set(m[1].toLowerCase(), { type: m[2], rest: (m[3] || '').trim() });
  }
  return cols;
}

/** Every column the DDL declares, from CREATEs and ALTERs alike. */
function declaredColumns(sqlite) {
  const files = ddlFiles(sqlite);
  const declared = new Map();

  for (const f of files) {
    const sql = fs.readFileSync(path.join(MIG, f), 'utf8');

    const createRe = /CREATE TABLE(?:\s+IF NOT EXISTS)?\s+"?(\w+)"?\s*\(([\s\S]*?)\n\s*\)\s*;/gi;
    let m;
    while ((m = createRe.exec(sql))) {
      const t = m[1].toLowerCase();
      if (!declared.has(t)) declared.set(t, new Map());
      for (const [name, def] of parseColumns(m[2])) {
        if (!declared.get(t).has(name)) declared.get(t).set(name, def);
      }
    }

    const alterRe = /ALTER TABLE\s+"?(\w+)"?\s+ADD COLUMN(?:\s+IF NOT EXISTS)?\s+"?(\w+)"?\s+([A-Za-z][\w()]*)\s*([^;]*);/gi;
    while ((m = alterRe.exec(sql))) {
      const t = m[1].toLowerCase();
      if (!declared.has(t)) declared.set(t, new Map());
      const col = m[2].toLowerCase();
      if (!declared.get(t).has(col)) declared.get(t).set(col, { type: m[3], rest: (m[4] || '').trim() });
    }
  }
  return declared;
}

function toPgType(t) {
  const u = (t || '').toUpperCase();
  if (/INT/.test(u)) return 'INTEGER';
  if (/REAL|FLOAT|DOUBLE/.test(u)) return 'DOUBLE PRECISION';
  if (/DECIMAL|NUMERIC/.test(u)) return u;
  if (/BOOLEAN/.test(u)) return 'BOOLEAN';
  if (/DATETIME|TIMESTAMP/.test(u)) return 'TIMESTAMP WITH TIME ZONE';
  if (/DATE/.test(u)) return 'DATE';
  if (/BLOB/.test(u)) return 'BYTEA';
  return 'TEXT';
}

function banner(driver, count) {
  return `-- Migration 069 (${driver}): restore columns declared in DDL but missing from the database
--
-- Tables are re-declared across migrations, and CREATE TABLE IF NOT EXISTS is a
-- no-op once the table exists, so later re-declarations that introduced columns
-- added nothing while still reporting success. marketplace_listings lost
-- latitude/longitude that way, breaking POST /marketplace and leaving its radius
-- filter matching everything.
--
-- Generated by scripts/repair-noop-creates.js, diffed against the LIVE schema
-- rather than inferred from migration order. ${count} column(s). Additive only:
-- nothing is dropped or retyped, so this cannot lose data and re-running is safe.

`;
}

async function main() {
  const db = require('../src/config/database');
  const declared = declaredColumns(true);

  // Real column lists from the engine, via PRAGMA table_info / information_schema.
  // Earlier revisions of this script parsed the DDL text instead and were wrong
  // four times running: inline `--` comments, ALTERs applied by later
  // migrations, and init.sql's execution order each defeated the parser in turn.
  const liveTables = new Set((await db.listTables()).map((t) => t.toLowerCase()));

  const lost = new Map();
  for (const [table, cols] of declared) {
    if (!liveTables.has(table)) continue; // whole table missing — migration 068 covers that
    const actual = new Set((await db.getTableColumns(table)).map((c) => c.name.toLowerCase()));
    for (const [name, def] of cols) {
      if (actual.has(name)) continue;
      if (/PRIMARY KEY/i.test(def.rest || '')) continue; // ALTER cannot add a PK
      if (!lost.has(table)) lost.set(table, []);
      lost.get(table).push({ col: name, ...def });
    }
  }

  // Not every missing column is a bug. Several are duplicate concepts under a
  // second name — carpool_rides has from_location/to_location but a later
  // migration declared origin/destination; community_posts has likes but
  // declares likes_count. Adding both would bloat the schema with synonyms.
  //
  // The ones that matter are those application code actually reads or writes:
  // there, the column's absence is a live runtime error. The rest are dead
  // declarations and are reported separately rather than migrated.
  const srcFiles = [];
  (function walk(dir) {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      if (['migrations', 'seeds', '__tests__', 'node_modules'].includes(e.name)) continue;
      const full = path.join(dir, e.name);
      if (e.isDirectory()) walk(full);
      else if (e.name.endsWith('.js')) srcFiles.push(full);
    }
  })(path.resolve(__dirname, '..', 'src'));

  const corpus = srcFiles.map((f) => fs.readFileSync(f, 'utf8')).join('\n');

  const dead = new Map();
  for (const [table, cols] of [...lost]) {
    const used = [];
    const unused = [];
    for (const c of cols) {
      // Look for the column as an identifier in SQL or object access.
      const re = new RegExp(`\\b${c.col}\\b`);
      (re.test(corpus) ? used : unused).push(c);
    }
    if (used.length) lost.set(table, used); else lost.delete(table);
    if (unused.length) dead.set(table, unused);
  }

  const deadCount = [...dead.values()].reduce((n, a) => n + a.length, 0);

  const tables = [...lost.keys()].sort();
  const total = tables.reduce((n, t) => n + lost.get(t).length, 0);
  console.log(`\n(${deadCount} further declared columns are referenced by no code — treated as dead declarations, not migrated.)`);

  console.log('\nDeclared columns missing from the live database');
  console.log('='.repeat(78));
  console.log('Verified against the live SQLite schema, not inferred from migration order.');
  console.log(`Tables affected: ${tables.length}   Columns missing: ${total}\n`);
  for (const t of tables) {
    const cols = lost.get(t).map((c) => c.col);
    console.log(`  ${t.padEnd(30)} ${String(cols.length).padStart(2)}  [${cols.slice(0, 6).join(', ')}${cols.length > 6 ? ', ...' : ''}]`);
  }

  if (!process.argv.includes('--write')) {
    console.log('\nReport only. Pass --write to emit migration 069.\n');
    return;
  }

  const sq = [];
  const pg = [];
  for (const t of tables) {
    sq.push(`-- ${t}`);
    pg.push(`-- ${t}`);
    for (const c of lost.get(t)) {
      const rest = (c.rest || '').replace(/AUTOINCREMENT/ig, '').replace(/PRIMARY KEY/ig, '').trim();
      sq.push(`ALTER TABLE ${t} ADD COLUMN ${c.col} ${c.type}${rest ? ' ' + rest : ''};`);

      const pt = toPgType(c.type);
      let pr = rest;
      if (pt === 'BOOLEAN') pr = pr.replace(/DEFAULT\s+1\b/i, 'DEFAULT TRUE').replace(/DEFAULT\s+0\b/i, 'DEFAULT FALSE');
      pr = pr.replace(/DEFAULT\s+\(?datetime\('now'\)\)?/i, 'DEFAULT CURRENT_TIMESTAMP');
      pg.push(`ALTER TABLE ${t} ADD COLUMN IF NOT EXISTS ${c.col} ${pt}${pr ? ' ' + pr : ''};`);
    }
    sq.push('');
    pg.push('');
  }

  fs.writeFileSync(path.join(MIG, '069_repair_noop_creates.sqlite.sql'), banner('SQLite', total) + sq.join('\n'));
  fs.writeFileSync(path.join(MIG, '069_repair_noop_creates.sql'), banner('PostgreSQL', total) + pg.join('\n'));
  console.log(`\nWritten: 069_repair_noop_creates.sql and .sqlite.sql (${total} columns)\n`);
}

main().catch((e) => { console.error(e); process.exit(1); });
